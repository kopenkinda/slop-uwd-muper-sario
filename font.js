  const LINE = 9
  const glyphs = { ' ': [] } // character -> horizontal pixel runs [x, y, length]
  for (const sheet of SHEETS.trim().split('\n\n')) {
    const [chars, ...rows] = sheet.split('\n')
    ;[...chars].forEach((ch, i) => {
      glyphs[ch] = rows.flatMap((row, y) =>
        [...row.slice(i * 6, i * 6 + 5).matchAll(/#+/g)].map((m) => [m.index, y, m[0].length]))
    })
  }
  // Latin letters that look exactly like a Cyrillic one reuse its shape.
  ;[...'ABCEHKMOPTX'].forEach((ch, i) => (glyphs[ch] = glyphs['АВСЕНКМОРТХ'[i]]))

  const lines = (text) => String(text).toUpperCase().split('\n').map((line) => [...line])
  const width = (line, scale) => Math.max(0, line.length * 6 - 1) * scale

  function measure(text, scale = 1) {
    return Math.max(...lines(text).map((line) => width(line, scale)))
  }

  function draw(ctx, text, x, y, { color = '#f6ecd4', scale = 1, align = 'left', shadow = null } = {}) {
    if (shadow) draw(ctx, text, x + scale, y + scale, { color: shadow, scale, align })
    ctx.fillStyle = color
    lines(text).forEach((line, row) => {
      const w = width(line, scale)
      let cx = Math.round(x) - (align === 'center' ? w >> 1 : align === 'right' ? w : 0)
      const top = Math.round(y) + row * LINE * scale
      for (const ch of line) {
        for (const [gx, gy, len] of glyphs[ch] || glyphs['?'])
          ctx.fillRect(cx + gx * scale, top + gy * scale, len * scale, scale)
        cx += 6 * scale
      }
    })
  }

  return { draw, measure, LINE }
